#!/usr/bin/env python3
"""make_urban_world.py — generate worlds/sar_urban.sdf from the shared
building list in urban_buildings.py, reusing the open-field preamble so
the physics/sensor/spherical-coordinate setup stays identical.

The world's internal <world name> is 'sar_urban'; scripts select it via
the SAR_WORLD environment variable (default 'sar_open_field').

Usage:  python3 worlds/make_urban_world.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from urban_buildings import sdf_models, BUILDINGS  # noqa: E402

OPEN = HERE / "sar_open_field.sdf"
OUT = HERE / "sar_urban.sdf"


def preamble():
    """Everything from the open-field world up to and including the
    ground_plane model, with the world renamed to sar_urban."""
    text = OPEN.read_text()
    start = text.index("<world ")
    end = text.index("</model>", text.index('name="ground_plane"')) + len("</model>")
    block = text[start:end]
    return block.replace('<world name="sar_open_field">',
                         '<world name="sar_urban">')


ROBOTS = """
    <!-- Robots (static includes so the GUI renders them; motion is
         cmd_vel/set_pose). Placed in the clear zone inside the inner
         building ring (|x|,|y| < ~34 m). -->
    <include>
      <name>sar_uav</name>
      <pose>0 0 40 0 0 0</pose>
      <uri>model://x500_base</uri>
      <static>true</static>
    </include>

    <include>
      <name>sar_ground_alpha</name>
      <pose>15 0 0 0 0 0</pose>
      <uri>model://sar_burger</uri>
    </include>

    <include>
      <name>sar_ground_bravo</name>
      <pose>-15 0 0 0 0 0</pose>
      <uri>model://sar_burger</uri>
    </include>
"""


def main():
    sdf = (
        '<?xml version="1.0" ?>\n'
        "<!-- sar_urban.sdf — AUTO-GENERATED by make_urban_world.py.\n"
        "     Building geometry is defined in urban_buildings.py, which is\n"
        "     also imported by channel_bridge.py for the NLoS line-of-sight\n"
        "     check, so the radio and the visuals share one source of truth.\n"
        "     Edit urban_buildings.py and re-run the generator; do not hand-\n"
        "     edit this file. -->\n"
        '<sdf version="1.9">\n  '
        + preamble()
        + "\n\n    <!-- ── Urban blocks (NLoS obstacles) ─────────────────── -->\n"
        + sdf_models()
        + "\n"
        + ROBOTS
        + "\n  </world>\n</sdf>\n"
    )
    OUT.write_text(sdf)
    print(f"wrote {OUT} ({len(BUILDINGS)} buildings)")


if __name__ == "__main__":
    main()
