#!/usr/bin/env python3
"""make_forest_world.py — generate worlds/sar_forest.sdf from the shared
tree list in forest_trees.py, reusing the open-field preamble so the
physics/sensor/spherical-coordinate setup stays identical.

The world's internal <world name> is 'sar_forest'; scripts select it via
the SAR_WORLD environment variable (default 'sar_open_field').

Usage:  python3 worlds/make_forest_world.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from forest_trees import sdf_models, TREES  # noqa: E402

OPEN = HERE / "sar_open_field.sdf"
OUT = HERE / "sar_forest.sdf"


def preamble():
    """Everything from the open-field world up to and including the
    ground_plane model, with the world renamed to sar_forest."""
    text = OPEN.read_text()
    start = text.index("<world ")
    end = text.index("</model>", text.index('name="ground_plane"')) + len("</model>")
    block = text[start:end]
    return block.replace('<world name="sar_open_field">',
                         '<world name="sar_forest">')


ROBOTS = """
    <!-- Robots. UAV hovers over the clearing at the forest centre; the two
         burgers spawn in the same clearing and drive out between the
         trunks. Motion is cmd_vel/set_pose (static includes so the GUI
         renders them). -->
    <include>
      <name>sar_uav</name>
      <pose>0 0 40 0 0 0</pose>
      <uri>model://x500_base</uri>
      <static>true</static>
    </include>

    <include>
      <name>sar_ground_alpha</name>
      <pose>15 0 0 0 0 0</pose>
      <uri>model://sar_burger</uri>
    </include>

    <include>
      <name>sar_ground_bravo</name>
      <pose>-15 0 0 0 0 0</pose>
      <uri>model://sar_burger</uri>
    </include>
"""


def main():
    sdf = (
        '<?xml version="1.0" ?>\n'
        "<!-- sar_forest.sdf — AUTO-GENERATED by make_forest_world.py.\n"
        "     Tree geometry is defined in forest_trees.py, which is also\n"
        "     imported by channel_bridge.py for the Weissberger foliage-\n"
        "     depth loss, so the radio and the visuals share one source of\n"
        "     truth. Edit forest_trees.py and re-run the generator; do not\n"
        "     hand-edit this file. -->\n"
        '<sdf version="1.9">\n  '
        + preamble()
        + "\n\n    <!-- ── Forest (foliage clutter) ────────────────────── -->\n"
        + sdf_models()
        + "\n"
        + ROBOTS
        + "\n  </world>\n</sdf>\n"
    )
    OUT.write_text(sdf)
    print(f"wrote {OUT} ({len(TREES)} trees)")


if __name__ == "__main__":
    main()
