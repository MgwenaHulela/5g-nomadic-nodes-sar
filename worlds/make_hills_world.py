#!/usr/bin/env python3
"""make_hills_world.py — generate worlds/sar_hills.sdf from the shared hill
list in terrain_hills.py, reusing the open-field preamble so the
physics/sensor/spherical-coordinate setup stays identical.

The world's internal <world name> is 'sar_hills'; scripts select it via the
SAR_WORLD environment variable (default 'sar_open_field').

Usage:  python3 worlds/make_hills_world.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from terrain_hills import sdf_models, HILLS  # noqa: E402

OPEN = HERE / "sar_open_field.sdf"
OUT = HERE / "sar_hills.sdf"


def preamble():
    """Everything from the open-field world up to and including the
    ground_plane model, with the world renamed to sar_hills."""
    text = OPEN.read_text()
    start = text.index("<world ")
    end = text.index("</model>", text.index('name="ground_plane"')) + len("</model>")
    block = text[start:end]
    return block.replace('<world name="sar_open_field">',
                         '<world name="sar_hills">')


ROBOTS = """
    <!-- Robots. UAV hovers over the central flat; the burgers spawn there
         and drive out between the hills. Motion is cmd_vel/set_pose. -->
    <include>
      <name>sar_uav</name>
      <pose>0 0 40 0 0 0</pose>
      <uri>model://x500_base</uri>
      <static>true</static>
    </include>

    <include>
      <name>sar_ground_alpha</name>
      <pose>15 0 0 0 0 0</pose>
      <uri>model://sar_burger</uri>
    </include>

    <include>
      <name>sar_ground_bravo</name>
      <pose>-15 0 0 0 0 0</pose>
      <uri>model://sar_burger</uri>
    </include>
"""


def main():
    sdf = (
        '<?xml version="1.0" ?>\n'
        "<!-- sar_hills.sdf — AUTO-GENERATED by make_hills_world.py.\n"
        "     Hill geometry is defined in terrain_hills.py, which is also\n"
        "     imported by channel_bridge.py for the ITU-R P.526 knife-edge\n"
        "     diffraction loss, so the radio and the visuals share one\n"
        "     source of truth. Edit terrain_hills.py and re-run the\n"
        "     generator; do not hand-edit this file. -->\n"
        '<sdf version="1.9">\n  '
        + preamble()
        + "\n\n    <!-- ── Hills (terrain shadowing) ─────────────────────── -->\n"
        + sdf_models()
        + "\n"
        + ROBOTS
        + "\n  </world>\n</sdf>\n"
    )
    OUT.write_text(sdf)
    print(f"wrote {OUT} ({len(HILLS)} hills)")


if __name__ == "__main__":
    main()
