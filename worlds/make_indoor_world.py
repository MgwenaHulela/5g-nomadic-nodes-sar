#!/usr/bin/env python3
"""make_indoor_world.py — generate worlds/sar_indoor.sdf from the shared
wall list in indoor_building.py, reusing the open-field preamble so the
physics/sensor/spherical-coordinate setup stays identical.

The world's internal <world name> is 'sar_indoor'; scripts select it via
the SAR_WORLD environment variable (default 'sar_open_field').

Usage:  python3 worlds/make_indoor_world.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from indoor_building import sdf_models, WALLS  # noqa: E402

OPEN = HERE / "sar_open_field.sdf"
OUT = HERE / "sar_indoor.sdf"


def preamble():
    """Everything from the open-field world up to and including the
    ground_plane model, with the world renamed to sar_indoor."""
    text = OPEN.read_text()
    start = text.index("<world ")
    end = text.index("</model>", text.index('name="ground_plane"')) + len("</model>")
    block = text[start:end]
    return block.replace('<world name="sar_open_field">',
                         '<world name="sar_indoor">')


ROBOTS = """
    <!-- Robots. UAV hovers over the building; the burgers spawn just south
         of the entry door and drive IN through it to search room by room.
         Motion is cmd_vel/set_pose. -->
    <include>
      <name>sar_uav</name>
      <pose>0 0 40 0 0 0</pose>
      <uri>model://x500_base</uri>
      <static>true</static>
    </include>

    <include>
      <name>sar_ground_alpha</name>
      <pose>0 -14 0 0 0 0</pose>
      <uri>model://sar_burger</uri>
    </include>

    <include>
      <name>sar_ground_bravo</name>
      <pose>7 -14 0 0 0 0</pose>
      <uri>model://sar_burger</uri>
    </include>
"""


def main():
    sdf = (
        '<?xml version="1.0" ?>\n'
        "<!-- sar_indoor.sdf — AUTO-GENERATED by make_indoor_world.py.\n"
        "     Wall geometry is defined in indoor_building.py, which is also\n"
        "     imported by channel_bridge.py for the 3GPP O2I building-\n"
        "     penetration loss, so the radio and the visuals share one\n"
        "     source of truth. Edit indoor_building.py and re-run the\n"
        "     generator; do not hand-edit this file. -->\n"
        '<sdf version="1.9">\n  '
        + preamble()
        + "\n\n    <!-- ── Enterable building (indoor search) ────────────── -->\n"
        + sdf_models()
        + "\n"
        + ROBOTS
        + "\n  </world>\n</sdf>\n"
    )
    OUT.write_text(sdf)
    print(f"wrote {OUT} ({len(WALLS)} walls)")


if __name__ == "__main__":
    main()
