def tex_table(path, header, rows, colspec, note=None):
    """Write a booktabs tabular fragment (no float) to path."""
    with open(path, "w") as f:
        f.write(f"% generated by {path.rsplit('/', 1)[-1].replace('.tex', '.py')} -- do not edit\n")
        f.write(f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n")
        f.write(" & ".join(header) + " \\\\\n\\midrule\n")
        for r in rows:
            f.write(" & ".join(str(c) for c in r) + " \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
        if note:
            f.write(f"% {note}\n")
